// The pure side of tools/labels-catalogue.mjs: the code catalogue (src/tools/codes.ts) against the
// shipped labels (config/labels.json, its two sections joined) and the contract's list of reason codes (docs/prompt-contract.md).
// Every `skill` code needs a `tools.result.reasons.<code>`, every `wake` code a `wake.feedback.codes.<code>`,
// no label may lack its code (`other` is the one fallback), and a label may only name values its code takes.
// The contract keeps a generated table between two markers; `renderCodesTable` writes it.

export const TABLE_BEGIN =
  '<!-- codes:begin (generated by tools/labels-catalogue.mjs --write; do not edit by hand) -->';
export const TABLE_END = '<!-- codes:end -->';

/** The placeholders (`{name}`) a template holds. */
export const placeholdersOf = (template) => [...String(template).matchAll(/\{(\w+)\}/g)].map((match) => match[1]);

const own = (object, key) => object && typeof object === 'object' && Object.hasOwn(object, key);

/**
 * The contract's table of the catalogue: one row per code, its status, its values and where its wording is.
 * @param {Record<string, { status: string, group: string, params: string[] }>} catalogue
 * @returns {string}  The lines between (and including) the two markers.
 */
export function renderCodesTable(catalogue) {
  const where = {
    skill: (code) => `\`tools.result.reasons.${code}\``,
    wake: (code) => `\`wake.feedback.codes.${code}\``,
    internal: () => 'none (internal)',
    ok: () => 'none (success)',
  };
  const rows = Object.entries(catalogue).map(
    ([code, entry]) =>
      `| \`${code}\` | ${entry.status} | ${entry.params.length > 0 ? entry.params.map((param) => `{${param}}`).join(' ') : '-'} | ${where[entry.group](code)} |`
  );
  return [TABLE_BEGIN, '| Code | Status | Values | Wording |', '|---|---|---|---|', ...rows, TABLE_END].join('\n');
}

/**
 * Everything wrong between the catalogue, the labels and the contract; [] when they agree.
 * @param {{ catalogue: object, labels: object, docs?: string|null }} input
 * @returns {string[]}
 */
export function catalogueProblems({ catalogue, labels, docs = null }) {
  const problems = [];
  const reasons = labels?.tools?.result?.reasons ?? {};
  const wake = labels?.wake?.feedback?.codes ?? {};
  for (const [code, entry] of Object.entries(catalogue)) {
    if (entry.group === 'skill') {
      if (!own(reasons, code) || typeof reasons[code] !== 'string' || !reasons[code])
        problems.push(`code ${code} has no labels.tools.result.reasons.${code}`);
      else
        for (const name of placeholdersOf(reasons[code]))
          if (!entry.params.includes(name))
            problems.push(`labels.tools.result.reasons.${code} names {${name}}, which the code does not take`);
    } else if (entry.group === 'wake') {
      if (!own(wake, code)) problems.push(`code ${code} has no labels.wake.feedback.codes.${code}`);
    } else if (own(reasons, code) || own(wake, code)) {
      problems.push(`code ${code} is ${entry.group} but has a label`);
    }
    for (const param of entry.params) {
      if (param === 'status') continue;
      if (!own(labels?.tools?.result?.params, param))
        problems.push(`code ${code} takes {${param}} but labels.tools.result.params.${param} is missing`);
    }
  }
  for (const code of Object.keys(reasons))
    if (code !== 'other' && catalogue[code]?.group !== 'skill')
      problems.push(`labels.tools.result.reasons.${code} has no catalogue code`);
  for (const code of Object.keys(wake))
    if (catalogue[code]?.group !== 'wake') problems.push(`labels.wake.feedback.codes.${code} has no catalogue code`);
  if (docs !== null) {
    const begin = docs.indexOf(TABLE_BEGIN);
    const end = docs.indexOf(TABLE_END);
    if (begin === -1 || end === -1) problems.push('docs/prompt-contract.md has no generated codes table');
    else if (docs.slice(begin, end + TABLE_END.length) !== renderCodesTable(catalogue))
      problems.push(
        'the codes table in docs/prompt-contract.md is out of date (run tools/labels-catalogue.mjs --write)'
      );
  }
  return problems;
}
