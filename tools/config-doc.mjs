#!/usr/bin/env node
// Prints docs/configuration.md to stdout: the prose of tools/config-doc.template.md with each marker
// `<!-- settings: <prefix> -->` replaced by the table of the schema's keys under that prefix (src/config/schema.ts).
// A key goes to the table of the longest prefix that holds it, and a key no marker holds, or a marker that holds no
// key, stops the run. tests/config-doc.test.ts fails while the committed document differs from the output:
//
//   node tools/config-doc.mjs > docs/configuration.md

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { CONFIG_SCHEMA } from '../src/config/schema.ts';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const TEMPLATE = path.join(ROOT, 'tools', 'config-doc.template.md');
const MARKER = /^<!-- settings: (\S+) -->$/;
const FIRST_LINE =
  '<!-- Generated by tools/config-doc.mjs from src/config/schema.ts and tools/config-doc.template.md. Edit those, then run node tools/config-doc.mjs > docs/configuration.md -->';

/**
 * `value` as one line of JSON with a space after each comma and inside each brace, as the tables print a default.
 * @param {unknown} value
 * @returns {string}
 */
function shown(value) {
  if (Array.isArray(value)) return `[${value.map(shown).join(', ')}]`;
  if (typeof value === 'object' && value !== null) {
    const entries = Object.entries(value);
    return entries.length === 0
      ? '{}'
      : `{ ${entries.map(([key, inner]) => `${JSON.stringify(key)}: ${shown(inner)}`).join(', ')} }`;
  }
  return JSON.stringify(value);
}

/**
 * The longest of `prefixes` that holds `key`, or null.
 * @param {string} key
 * @param {string[]} prefixes
 * @returns {string | null}
 */
function tableOf(key, prefixes) {
  let best = null;
  for (const prefix of prefixes)
    if ((key === prefix || key.startsWith(`${prefix}.`)) && (best === null || prefix.length > best.length))
      best = prefix;
  return best;
}

/**
 * @param {import('../src/config/schema.ts').SchemaEntry} entry
 * @returns {string}
 */
const row = (entry) =>
  `| \`${entry.key}\` | ${entry.types.join(', ')} | \`${shown(entry.default)}\` | ${entry.text.replaceAll('|', '\\|')} | \`${entry.reader}\` |`;

function main() {
  const lines = fs.readFileSync(TEMPLATE, 'utf8').split('\n');
  const prefixes = lines.flatMap((line) => MARKER.exec(line)?.slice(1, 2) ?? []);
  /** @type {Map<string, string[]>} */
  const rows = new Map(prefixes.map((prefix) => [prefix, []]));
  for (const entry of CONFIG_SCHEMA) {
    const prefix = tableOf(entry.key, prefixes);
    if (prefix === null) throw new Error(`no settings marker holds ${entry.key}`);
    rows.get(prefix)?.push(row(entry));
  }
  const out = [FIRST_LINE];
  for (const line of lines) {
    const prefix = MARKER.exec(line)?.[1];
    if (prefix === undefined) {
      out.push(line);
      continue;
    }
    const table = rows.get(prefix) ?? [];
    if (table.length === 0) throw new Error(`the settings marker ${prefix} holds no key`);
    out.push('| Key | Type | Default | What it does | Read by |', '|---|---|---|---|---|', ...table);
  }
  return out.join('\n');
}

process.stdout.write(main());
